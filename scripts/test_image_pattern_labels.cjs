const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '..', 'monitor.js'), 'utf8');
const context = vm.createContext({});
vm.runInContext(source.slice(source.indexOf('function imagePatternLabel('), source.indexOf('function renderImageSearch(')), context);
const event = {ruleId: 'daehan-recovery-pattern', stage: 'confirmation', completedAt: '2026-10-16T03:00:00Z', changePct: 2.9};
let item = context.imagePatternSummary(event);
assert.equal(item.label, '하락중 MA10이 MA40 돌파');
assert.equal(item.time, '10.16. 12:00');
assert.equal(item.change, '+2.9%');
assert.equal(item.direction, 'up');
item = context.imagePatternSummary({...event, ruleId: 'daesung-decline-ma40-recovery', stage: 'primary', changePct: -2.91});
assert.equal(item.label, '하락중 MA3가 MA40 돌파');
assert.equal(item.change, '-2.9%');
assert.equal(item.direction, 'down');
assert.equal(context.imagePatternLabel({...event, signalType: 'ma3Rise', clusterLines: [3,10,20,40], stage: 'primary'}), '4선 밀집후 MA3 1봉 상승');
assert.equal(context.imagePatternLabel({...event, signalType: 'ma3Rise', clusterLines: [3,10,20,40,60]}), '5선 밀집후 MA3 2봉 상승');
assert.equal(context.imagePatternLabel({...event, signalType: 'ma3Ma120', stage: 'primary'}), 'MA3가 MA120 재돌파');
assert.equal(context.imagePatternLabel({...event, signalType: 'ma3Ma120'}), '120MA아래로 3MA하락후 상승');
assert.equal(context.imagePatternLabel({...event, signalType: 'ma20Pyramid', stage: 'primary'}), '피라미드후 MA3 반등');
assert.equal(context.imagePatternLabel({...event, signalType: 'ma3Ma60Near', stage: 'primary'}), 'MA60 부근 MA3 반등');
assert.equal(context.imagePatternLabel({...event, signalType: 'ma3Ma60Near', stage: 'confirmation'}), 'MA60 부근 MA3 돌파 확인');
assert.equal(context.imagePatternLabel({...event, signalType: 'ma3Ma60Near', stage: 'watch'}), '피라미드형 상승가능성 검토');
assert.equal(context.imagePatternLabel({...event, signalType: 'ma20Pyramid'}), '피라미드후 MA3가 MA60 돌파');
assert.equal(context.imagePatternSummary({...event, signalType: 'ma20Pyramid', strongRise: true}).strength, '강한 상승 이력');
assert.equal(context.imagePatternSummary({...event, signalType: 'ma20Pyramid', strongRise: false}).strength, '');
assert.equal(context.imagePatternSummary({...event, strongRise: true}).strength, '');
assert.equal(context.imagePatternSummary({...event, changePct: null}).change, '등락률 미확인');
assert.equal(context.imagePatternSummary({...event, completedAt: 'invalid'}).time, '시각 미확인');
assert.equal(context.imagePatternSummary({...event, changePct: 0}).change, '0.0%');
console.log('Image labels passed: short pattern names, stage distinctions, KST completion time and signed capture return.');
